배열4 = [] 
for(let 임시=10; 임시>0; 임시-=2){ // 2씩 감소
    배열4.push(임시)
}
console.log(배열4) 

let 합계 = 0
// for를 통해서 배열 안에 들어있는 모든값을 사용
for ( let 방번호=0; 방번호 < 배열4.length; 방번호++){
    //console.log(배열4[방번호])
    합계 += 배열4[방번호]
}
