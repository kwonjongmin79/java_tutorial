let 배열 =[]

// 반복문은 유사한 코드를 연속으로 실행할 때 사용 while , for
// while : 조건이 fales 때까지 반복
let 숫자 = 0
while(숫자 < 5){
    배열.push(숫자)
    숫자 += 1 // 1씩 증가시켜 저장
}
console.log(배열) // [0, 1, 2, 3, 4]

// for : 조건이 fales 때까지 반복 (반복문을 소괄호안에 모두 넣어줌줌)
let 배열2 = []
for(let 임시=0; 임시<5; 임시++){ // =+= 1 과 ++ 같은 의미로 사용용
    배열2.push(임시)
}
console.log(배열2) // [0, 1, 2, 3, 4]

배열3 = [] // 0~4 => 1~5
for(let 임시=1; 임시<=5; 임시++){
    배열3.push(임시)
}
console.log(배열3) // [1, 2, 3, 4, 5]


배열3 = [] //
